/**
 * HowTo - the sign-up steps on the home page.
 *
 * Built from the same array the page renders, so the markup cannot describe a
 * step a reader cannot see. `text` is the step body, which is already written
 * as an instruction.
 */
export function howtoSchema(steps) {
  return {
    '@context': 'https://schema.org',
    '@type': 'HowTo',
    name: 'How to get started with Bitlionex Port',
    description:
      'Sign up, confirm your ID, add funds and follow your first signal. The first alert is two minutes away.',
    totalTime: 'PT2M',
    step: steps.map((s, i) => ({
      '@type': 'HowToStep',
      position: i + 1,
      name: s.title,
      text: s.body,
      url: `${SITE}/#get-started`,
    })),
  }
}

export function schemasFor(route, faqItems = [], steps = []) {
  const conf = seo[route] || seo['404']
  const names = conf.structuredData || []
  const out = []
  for (const name of names) {
    if (name === 'organization') out.push(ORG_SCHEMA)
    else if (name === 'website') out.push(WEBSITE_SCHEMA)
    else if (name === 'faq' && faqItems.length) out.push(faqSchema(faqItems))
    else if (name === 'webpage') out.push(webpageSchema(route))
    else if (name === 'service') out.push(SERVICE_SCHEMA)
    else if (name === 'howto' && steps.length) out.push(howtoSchema(steps))
  }
  return out
}
