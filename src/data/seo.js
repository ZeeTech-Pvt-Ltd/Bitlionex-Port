// One card per indexable route, generated by scripts/make-og.mjs from the
// `card` copy in the table below. Two routes share the home card on purpose:
// /thank-you and the 404 are noindex, so nothing should ever unfurl them, and
// if something does the fallback is a real card rather than a broken image.
export function ogImageFor(route) {
  const conf = seo[route] || seo['404']
  return `${SITE}/og-${conf.card ? route : 'home'}.png`
}

export function ogImageAltFor(route) {
  const conf = seo[route] || seo['404']
  const tagline = conf.card ? conf.card.note : ''
  // A colon, not a spaced hyphen. The house rule bans dashes used as dashes,
  // and "Bitlionex Port - What it does..." is exactly that - the copy suite
  // caught it on all seven cards.
  return tagline
    ? `${BRAND}: ${tagline}`
    : `${BRAND}, AI assisted trading signals for Australian traders`
}

